#include "nvc2_caps.h"

#include <cstdio>

namespace nvc2 {

const std::vector<std::pair<uint32_t, std::pair<const char *, const char *>>> &codec_table()
{
    /* names avoid Chrome's software prefixes (omx.google., c2.android., *.sw.dec):
     * MediaCodecUtil.java isSoftwareCodec(), chromium 149.0.7827.95 :114-130 */
    static const std::vector<std::pair<uint32_t, std::pair<const char *, const char *>>> t = {
        {NV_VIDEO_CODEC_VP9, {"c2.nvprolapse.vp9.decoder", "video/x-vnd.on2.vp9"}},
        {NV_VIDEO_CODEC_AV1, {"c2.nvprolapse.av1.decoder", "video/av01"}},
        {NV_VIDEO_CODEC_HEVC, {"c2.nvprolapse.hevc.decoder", "video/hevc"}},
        {NV_VIDEO_CODEC_H264, {"c2.nvprolapse.avc.decoder", "video/avc"}},
    };
    return t;
}

std::vector<CodecEntry> supported_codecs(NvVideoDevice *dev, std::string *error)
{
    std::vector<CodecEntry> v;
    for (const auto &e : codec_table()) {
        NvVideoCaps c{};
        int rc = nv_video_query_caps(dev, e.first, &c);
        if (rc != 0) {
            const char *le = nv_video_last_error();
            *error = std::string("nv_video_query_caps(") + e.second.first + ") = " + std::to_string(rc) + ": " +
                     (le ? le : "");
            return {};
        }
        if (!c.supported)
            continue;
        if (!c.max_width || !c.max_height || c.min_width > c.max_width || c.min_height > c.max_height ||
            !(c.bit_depth_mask & (1u << 8))) {
            *error = std::string("nv_video_query_caps(") + e.second.first +
                     ") reports supported with an unusable size range or without 8-bit";
            return {};
        }
        v.push_back(CodecEntry{e.first, e.second.first, e.second.second, c});
    }
    return v;
}

std::string media_codecs_xml(const std::vector<CodecEntry> &entries)
{
    std::string x;
    char buf[512];
    x += "<?xml version=\"1.0\" encoding=\"utf-8\" ?>\n";
    x += "<!-- Generated by nvc2-xmlgen from nv_video_query_caps() on this GPU. Do not edit:\n"
         "     regenerate (the service refuses to start when this file and the live caps differ). -->\n";
    x += "<MediaCodecs>\n    <Decoders>\n";
    for (const auto &e : entries) {
        /* NV12/P010 output: even dimensions */
        const uint32_t minw = (e.caps.min_width + 1) & ~1u, minh = (e.caps.min_height + 1) & ~1u;
        const uint32_t maxw = e.caps.max_width & ~1u, maxh = e.caps.max_height & ~1u;
        snprintf(buf, sizeof(buf),
                 "        <MediaCodec name=\"%s\" type=\"%s\">\n"
                 "            <Limit name=\"size\" min=\"%ux%u\" max=\"%ux%u\" />\n"
                 "            <Limit name=\"alignment\" value=\"2x2\" />\n"
                 "            <Limit name=\"block-size\" value=\"16x16\" />\n"
                 "            <Feature name=\"adaptive-playback\" />\n"
                 "        </MediaCodec>\n",
                 e.name, e.mime, minw, minh, maxw, maxh);
        x += buf;
    }
    x += "    </Decoders>\n</MediaCodecs>\n";
    return x;
}

std::string no_decoder_reason(const char *gpu_name)
{
    return std::string("hardware video decode: not available on ") + gpu_name +
           " (no NVDEC class this decoder supports; supported from Turing): Android software decoders are used";
}

std::string no_decoder_xml(const char *gpu_name)
{
    std::string reason = no_decoder_reason(gpu_name);
    size_t i;
    while ((i = reason.find("--")) != std::string::npos) /* not allowed inside an XML comment */
        reason.erase(i, 1);
    return "<?xml version=\"1.0\" encoding=\"utf-8\" ?>\n"
           "<!-- Generated by nvc2-xmlgen from nv_video_device_open() on this GPU: no hardware decoders.\n"
           "     " + reason + ".\n"
           "     Do not edit: regenerate (the service checks this file against the GPU at every start). -->\n"
           "<MediaCodecs>\n    <Decoders>\n    </Decoders>\n</MediaCodecs>\n";
}

} // namespace nvc2
